export function getDayMasterStrengthReading(dayMaster, strengthLevel) {
  const master = dayMasterStrengthMatrix[dayMaster]
  const result = master?.[strengthLevel]
  if (!master || !result) {
    throw new Error(`ยังไม่มีคำอ่านสำหรับดิถี ${dayMaster} ระดับ ${strengthLevel}`)
  }

  return {
    title: master.title,
    ...result,
    strengthPresentation: publicStrengthPresentation[strengthLevel]
  }
}
