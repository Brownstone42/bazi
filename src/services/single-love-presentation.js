// Editorial presentation of computed facts, not an additional prediction engine.
export function presentSingleLove({ topic, status, style, action, caution, friction, connection, monthTension }) {
  const uncertain = status === 'unresolved'
  const careful = friction || ['caution', 'mixed'].includes(status)
  const context = {
    supportive: 'ผลที่อ่านได้มีด้านที่สนับสนุนให้ลองเริ่มคุย แต่ยังต้องดูความพร้อมและการตอบรับจริง',
    caution: 'ผลที่อ่านได้มีด้านที่ควรระวัง จึงแนะนำให้ลดความคาดหวังและไม่เร่งความสัมพันธ์',
    mixed: 'ผลที่อ่านได้มีทั้งด้านสนับสนุนและด้านที่ควรระวัง จึงแนะนำให้เริ่มทีละน้อย',
    unresolved: 'ข้อมูลที่ใช้วิเคราะห์ยังให้ข้อสรุปไม่ชัด จึงยังบอกไม่ได้ว่าวันนี้เหมาะหรือไม่เหมาะเป็นพิเศษ',
    neutral: 'ผลที่อ่านได้ยังไม่เพิ่มเหตุผลชัดเจนให้เร่งหรือชะลอความสัมพันธ์เป็นพิเศษ',
  }[status] || 'ข้อมูลที่ใช้วิเคราะห์ยังไม่ชัดพอที่จะสรุปแนวโน้มของวันนี้'
  const connectionReason = connection
    ? 'มีองค์ประกอบที่ใช้ตีความเรื่องการเริ่มรู้จักกัน แต่ไม่ได้ยืนยันว่าจะได้พบใครหรือถูกใจกัน'
    : 'ยังไม่พบองค์ประกอบเฉพาะด้านการพบปะในส่วนที่ตรวจ ไม่ได้หมายความว่าวันนี้จะไม่มีโอกาสรู้จักใคร'
  const pace = uncertain ? 'ตัดสินใจจากความพร้อมและสถานการณ์จริง ไม่จำเป็นต้องฝืนเปลี่ยนแผนตามคำอ่าน'
    : careful ? 'เริ่มแบบสั้น ๆ และเว้นเวลาให้อีกฝ่ายตอบ ถ้ารู้สึกฝืนให้พักก่อน'
      : 'ลองเริ่มบทสนทนาหนึ่งครั้ง แล้วดูว่าอีกฝ่ายอยากคุยต่อหรือไม่'
  const mainCaution = friction ? 'อย่ารีบสรุปจากคำพูดสั้น ๆ หรือการตอบช้า ถ้าไม่แน่ใจให้ถามก่อน' : caution
  const answers = {
    'love-overview': {
      headline: uncertain ? 'วันนี้ยังไม่มีแนวโน้มชัดพอที่จะฟันธง' : careful ? 'ค่อย ๆ ทำความรู้จัก ไม่ต้องรีบหาคำตอบ' : 'ลองเปิดพื้นที่ให้บทสนทนาสบาย ๆ',
      answer: uncertain ? 'ใช้วันนี้ทำความรู้จักกันตามความพร้อมได้ โดยยังไม่ต้องตัดสินว่าจะพัฒนาไปได้แค่ไหน'
        : careful ? 'คำแนะนำวันนี้คือให้เวลากับการคุยและตรวจความเข้าใจกัน มากกว่าการรีบกำหนดความสัมพันธ์'
          : 'ลองคุยในแบบที่เป็นตัวเองและฟังอีกฝ่ายไปด้วย ความสัมพันธ์จะไปต่ออย่างไรให้ดูจากสิ่งที่เกิดขึ้นจริง',
      actions: [action, pace], caution: mainCaution,
      reasons: [context, friction ? 'ส่วนที่อ่านเรื่องความสัมพันธ์มีเงื่อนไขให้ระวังจังหวะไม่ตรงกัน ไม่ใช่คำทำนายว่าจะมีปัญหา' : connectionReason],
    },
    'love-meet': {
      headline: uncertain ? 'พบคนใหม่ได้ตามความพร้อม ยังไม่ชี้ว่าเหมาะเป็นพิเศษ' : careful ? 'พบได้ แต่เลือกนัดสั้น ๆ ที่ไม่กดดัน' : 'ลองจัดโอกาสรู้จักคนใหม่แบบสบาย ๆ',
      answer: 'ถ้าอยากพบคนใหม่ ให้เลือกกิจกรรมที่สนใจจริงและไม่ต้องฝืนตัวเอง คำอ่านไม่ได้รับรองว่านัดจะราบรื่นหรือพัฒนาเป็นความรัก',
      actions: ['เลือกกิจกรรมหรือวงสนทนาที่มีเรื่องสนใจร่วมกัน', pace],
      caution: 'อย่ารับปากนัดหรือฝืนไปเพียงเพราะคิดว่าวันนี้ต้องใช้โอกาสให้คุ้ม',
      reasons: [connectionReason, context],
    },
    'love-charm': {
      headline: `ลอง${style}`,
      answer: 'ใช้เป็นไอเดียในการคุยวันนี้ ไม่ต้องเปลี่ยนตัวเองหรือพยายามทำให้อีกฝ่ายชอบ',
      actions: [action, careful ? 'ลดความเข้มของการแสดงออก แล้วเพิ่มเวลาฟังอีกฝ่าย' : 'สังเกตการตอบรับและเปิดพื้นที่ให้อีกฝ่ายได้เล่าเรื่องของตัวเอง'],
      caution,
      reasons: ['วิธีคุยนี้มาจากลักษณะการแสดงออกที่ใช้ตีความสำหรับวันที่เลือก ไม่ใช่ข้อสรุปบุคลิกถาวรหรือความรู้สึกของอีกฝ่าย', context],
    },
    'love-caution': {
      headline: friction ? 'ตรวจความเข้าใจก่อนรีบสรุป' : 'ระวังจังหวะการสื่อสารของตัวเอง',
      answer: mainCaution,
      actions: ['ถ้าบทสนทนาไม่ชัด ให้ถามตรง ๆ อย่างสุภาพแทนการทดสอบใจ', 'ถ้ารู้สึกกดดัน ให้พักและกลับมาคุยเมื่อทั้งสองฝ่ายพร้อม'],
      caution: 'อย่าใช้คำอ่านเป็นหลักฐานว่าอีกฝ่ายไม่จริงใจหรือความสัมพันธ์จะมีปัญหา',
      reasons: [friction ? 'พบเงื่อนไขที่ตีความเป็นเรื่องการปรับจังหวะเข้าหากัน จึงเน้นการถามให้ชัดมากกว่าการคาดเดา' : 'ยังไม่พบเงื่อนไขขัดแย้งโดยตรงในส่วนความสัมพันธ์ที่ตรวจ จึงเน้นข้อควรระวังจากวิธีสื่อสารแทน ไม่ได้รับรองว่าจะไม่มีปัญหา', context],
    },
    'love-attraction': {
      headline: 'ยังบอกไม่ได้ว่าวันนี้จะเจอคนที่ถูกใจ',
      answer: uncertain ? 'วันนี้ยังไม่มีแนวโน้มชัดพอที่จะฟันธง การได้เจอใครและถูกใจกันยังขึ้นกับโอกาสพบปะและความรู้สึกของทั้งสองคน'
        : connection ? 'มีเหตุผลให้ลองเปิดโอกาสทำความรู้จัก แต่ยังสรุปไม่ได้ว่าจะเจอคนที่ชอบหรือรู้สึกตรงกัน'
          : 'ยังไม่มีแนวโน้มเฉพาะเรื่องนี้ชัดพอ ไม่ได้หมายความว่าจะไม่เจอคนที่ถูกใจ',
      actions: ['ถ้าอยากเปิดโอกาส ลองร่วมกิจกรรมที่ชอบหรือเริ่มคุยอย่างสุภาพ', 'ดูความสนใจที่อีกฝ่ายแสดงจริง แล้วค่อยตัดสินใจว่าจะรู้จักกันต่อไหม'],
      caution: 'อย่ารีบถือว่าความประทับใจแรกคือความเข้ากันได้ หรือแปลความสุภาพว่าเป็นความสนใจเชิงรัก',
      reasons: [connectionReason, context],
    },
  }
  const result = answers[topic]
  if (!result) throw new Error('ไม่พบรูปแบบคำตอบสำหรับคำถามนี้')
  if (monthTension) result.reasons.push('คำอ่านของวันนี้กับช่วงเดือนให้แนวทางการแสดงออกต่างกัน จึงควรเลือกจังหวะคุยและเวลาพักที่เหมาะกับตัวเอง')
  return result
}
