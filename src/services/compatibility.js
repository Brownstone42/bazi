function branchSignal(firstChart, secondChart, focus, hasBirthTime) {
  const positionsByFocus = {
    love: ['day', 'month', 'year', 'hour'],
    family: ['day', 'month', 'year', 'hour'],
    work: ['month', 'day', 'year', 'hour'],
    friendship: ['year', 'month', 'day', 'hour'],
    overview: ['day', 'month', 'year', 'hour']
  }
  const positions = positionsByFocus[focus].filter((position) => position !== 'hour' || hasBirthTime)
  let support = 0
  let challenge = 0

  positions.forEach((position, index) => {
    const key = `${firstChart.pillars[position].branch}${secondChart.pillars[position].branch}`
    const weight = positions.length - index
    if (supportiveBranches.has(key)) support += weight
    if (challengingBranches.has(key)) challenge += weight
  })

  if (support > challenge) return 'supportive'
  if (challenge > support) return 'challenging'
  return 'mixed'
}

export function interpretCompatibility(firstChart, secondChart, options) {
  const focus = focusCopy[options.focus] ?? focusCopy.overview
  const dynamic = elementDynamic(firstChart.dayMaster.element, secondChart.dayMaster.element)
  const signal = branchSignal(firstChart, secondChart, options.focus, options.hasBirthTime)
  const connection = signal === 'supportive'
    ? focus.smooth
    : signal === 'challenging'
      ? `${focus.smooth} อย่างไรก็ตาม ${focus.friction}`
      : `${focus.smooth} ${focus.friction}`

  return {
    focusLabel: focus.label,
    headline: focus.headline,
    summary: `${dynamic.text} ${relationshipTone[options.relationship] ?? ''}`.trim(),
    connection,
    communication: dynamic.communication,
    shouldDo: focus.action,
    shouldAvoid: focus.avoid,
    confidence: options.hasBirthTime ? 'ข้อมูลครบทั้งสองฝ่าย' : 'อ่านจากข้อมูลที่ทราบ',
    timeWarning: options.hasBirthTime
      ? null
      : 'ไม่ทราบเวลาเกิดของอีกฝ่าย คำอ่านนี้จึงเน้นรูปแบบหลักของความสัมพันธ์ รายละเอียดเกี่ยวกับชีวิตส่วนตัว เป้าหมายระยะยาว และวิธีแสดงออกบางส่วนอาจคลาดเคลื่อนได้'
  }
}
